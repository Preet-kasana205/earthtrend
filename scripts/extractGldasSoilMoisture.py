from __future__ import annotations

import argparse
import csv
import json
import math
import sys
from datetime import date
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "src" / "data" / "raw"
OUT = ROOT / "src" / "data" / "gldasSoilMoistureData.ts"
REGIONS = (
    {
        "name": "Rajasthan",
        "file": "g4.areaAvgTimeSeries.GLDAS_NOAH025_M_2_1_SoilMoi0_10cm_inst.20000101-20251231.69E_23N_78E_30N.csv",
        "user_bbox": "69,23,78,30",
        "data_bbox": "69.125,23.125,77.875,29.875",
    },
    {
        "name": "Assam",
        "file": "g4.areaAvgTimeSeries.GLDAS_NOAH025_M_2_1_SoilMoi0_10cm_inst.20000101-20251231.89E_24N_96E_28N.csv",
        "user_bbox": "89,24,96,28",
        "data_bbox": "89.125,24.125,95.875,27.875",
    },
)


def expected_months() -> list[date]:
    return [date(year, month, 1) for year in range(2000, 2026) for month in range(1, 13)]


def read_region(region: dict[str, str]) -> tuple[list[dict[str, Any]], dict[str, str]]:
    path = RAW / region["file"]
    lines = path.read_text(encoding="utf-8-sig").splitlines()
    header_index = next((i for i, line in enumerate(lines) if line.lower().startswith("time,")), None)
    if header_index is None:
        raise ValueError(f"{path.name}: no Giovanni time-series table header")

    metadata: dict[str, str] = {}
    for line in lines[:header_index]:
        row = next(csv.reader([line]))
        if len(row) > 1:
            metadata[row[0].strip().rstrip(":")] = row[1].strip()

    title = metadata.get("Title", "")
    if "GLDAS_NOAH025_M_2_1_SoilMoi0_10cm_inst" not in path.name or "GLDAS (monthly)" not in title:
        raise ValueError(f"{path.name}: source is not the requested monthly GLDAS Noah v2.1 0–10 cm product")
    if "M_2_0" in path.name or "v2.0" in title:
        raise ValueError(f"{path.name}: GLDAS v2.0 is not accepted")
    if metadata.get("User Bounding Box") != region["user_bbox"] or metadata.get("Data Bounding Box") != region["data_bbox"]:
        raise ValueError(f"{path.name}: bounding box does not match {region['name']}")
    if metadata.get("User Start Date") != "2000-01-01T00:00:00Z" or metadata.get("User End Date") != "2025-12-31T23:59:59Z":
        raise ValueError(f"{path.name}: requested period metadata must be Jan 2000–Dec 2025")

    reader = csv.DictReader(lines[header_index:])
    if reader.fieldnames is not None:
        reader.fieldnames = [name.strip() for name in reader.fieldnames]
    if reader.fieldnames != ["time", "mean_GLDAS_NOAH025_M_2_1_SoilMoi0_10cm_inst"]:
        raise ValueError(f"{path.name}: unexpected columns {reader.fieldnames!r}")
    result: list[dict[str, Any]] = []
    for row in reader:
        raw_date = (row.get("time") or "").strip()
        raw_value = (row.get("mean_GLDAS_NOAH025_M_2_1_SoilMoi0_10cm_inst") or "").strip()
        if not raw_date and not raw_value:
            continue
        if not raw_date or not raw_value:
            raise ValueError(f"{path.name}: incomplete observation row {row!r}")
        observation_date = date.fromisoformat(raw_date[:10])
        if observation_date.day != 1:
            raise ValueError(f"{path.name}: monthly timestamp is not on day 1: {raw_date}")
        try:
            value = float(raw_value)
        except ValueError as error:
            raise ValueError(f"{path.name}: non-numeric value {raw_value!r} at {raw_date}") from error
        if not math.isfinite(value) or value == -9999:
            raise ValueError(f"{path.name}: missing/fill or non-finite observation at {raw_date}: {raw_value}")
        result.append({
            "region": region["name"],
            "date": observation_date.strftime("%Y-%m"),
            "year": observation_date.year,
            "month": observation_date.month,
            "value": value,
        })

    dates = [date.fromisoformat(f"{row['date']}-01") for row in result]
    expected = expected_months()
    if len(result) != 312 or dates != expected or len(set(dates)) != 312:
        duplicate_count = len(dates) - len(set(dates))
        missing_count = len(set(expected) - set(dates))
        raise ValueError(f"{path.name}: expected 312 continuous unique months; got {len(result)}, duplicates={duplicate_count}, missing={missing_count}")
    return result, metadata


def render(points: list[dict[str, Any]]) -> str:
    body = json.dumps(points, ensure_ascii=False, indent=2, allow_nan=False)
    return (
        "// Generated by scripts/extractGldasSoilMoisture.py from the preserved NASA Giovanni CSV files.\n"
        "// GLDAS Noah v2.1 monthly soil moisture content, 0–10 cm, kg/m2.\n"
        "export type SoilMoistureRegion = \"Rajasthan\" | \"Assam\";\n\n"
        "export interface GldasSoilMoisturePoint {\n"
        "  region: SoilMoistureRegion;\n"
        "  date: string;\n"
        "  year: number;\n"
        "  month: number;\n"
        "  value: number;\n"
        "}\n\n"
        f"export const gldasSoilMoisture: GldasSoilMoisturePoint[] = {body};\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Validate and extract NASA GLDAS v2.1 monthly soil moisture from original Giovanni CSV files.")
    parser.add_argument("--check", action="store_true", help="Validate raw sources and check the generated TypeScript module without writing it.")
    args = parser.parse_args()
    all_points: list[dict[str, Any]] = []
    validated: list[tuple[dict[str, str], list[dict[str, Any]], dict[str, str]]] = []
    for region in REGIONS:
        points, metadata = read_region(region)
        validated.append((region, points, metadata))
        all_points.extend(points)

    generated = render(all_points)
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8-sig") != generated:
            raise ValueError(f"Generated module is stale or missing: {OUT.relative_to(ROOT).as_posix()}")
        action = "checked; typed module matches both raw CSVs"
    else:
        OUT.write_text(generated, encoding="utf-8")
        action = "extracted typed module from both raw CSVs"

    print("NASA GLDAS v2.1 raw-data validation:")
    for region, points, metadata in validated:
        values = [point["value"] for point in points]
        print(f"  {region['name']}: 312 monthly observations, {points[0]['date']} through {points[-1]['date']}; unique=312; duplicates=0; missing months=0; missing/non-numeric values=0")
        print(f"    bounds: requested [{metadata['User Bounding Box']}], data [{metadata['Data Bounding Box']}]; mean={sum(values) / len(values):.6f} kg/m2; range={min(values):.6f} - {max(values):.6f} kg/m2")
    print(f"  Product: NASA GLDAS Noah v2.1 | soil moisture content 0-10 cm | monthly | kg/m2; units per requested product metadata")
    print(f"  Result: {action}.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except Exception as error:
        print(f"GLDAS extraction validation failed: {error}", file=sys.stderr)
        sys.exit(1)
